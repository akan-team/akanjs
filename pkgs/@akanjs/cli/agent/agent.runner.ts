export type AgentTarget = "cursor" | "agents-md" | "claude";

const targetPaths: Record<AgentTarget, string> = {
  cursor: ".cursor/rules/akan.mdc",
  "agents-md": "AGENTS.md",
  claude: "CLAUDE.md",
};

// Scaffolded by `akan create-workspace` to show the conventions; not product code, so the guide asks for removal.
const SAMPLE_ARTIFACTS = [
  { probe: "lib/task/task.constant.ts", target: "lib/task", label: "sample database module" },
  { probe: "lib/_noti/noti.service.ts", target: "lib/_noti", label: "sample service module" },
  {
    probe: "lib/__scalar/workHistory/workHistory.dictionary.ts",
    target: "lib/__scalar/workHistory",
    label: "sample scalar module",
  },
  { probe: "page/task/_index.tsx", target: "page/task", label: "sample task pages" },
] as const;
const DEFAULT_INDEX_MARKER = "Akan.js template";

const renderSampleCleanup = async (workspace: Workspace, appNames: string[]) => {
  const items: string[] = [];
  for (const appName of appNames) {
    for (const artifact of SAMPLE_ARTIFACTS) {
      if (await workspace.exists(`apps/${appName}/${artifact.probe}`)) {
        items.push(
          `- \`apps/${appName}/${artifact.target}\` — ${artifact.label}; delete it once you no longer need the reference.`,
        );
      }
    }
    const indexPath = `apps/${appName}/page/_index.tsx`;
    if (await workspace.exists(indexPath)) {
      const content = await workspace.readFile(indexPath).catch(() => "");
      if (content.includes(DEFAULT_INDEX_MARKER)) {
        items.push(`- \`${indexPath}\` — default Akan landing page; replace it with your own home page.`);
      }
    }
  }
  if (items.length === 0) return "";
  return `## Start Clean (Remove Scaffolded Samples)

This workspace was scaffolded with reference samples so the Akan conventions are visible in real code. They are
not part of your product. Before building real features, remove the samples below and run \`akan sync <app>\`:

${items.join("\n")}

Keep a sample only while you are still learning its pattern; delete it once your own modules cover the same ground.

`;
};

// Framework recipes only: app/lib recipes live in each scope's own AGENTS.md, so this always-loaded file does not
// grow with the app count and never lists a recipe the reader cannot import.
const renderRecipeIndex = async (workspace: Workspace) => {
  const sources = await collectRecipeSources(`${workspace.workspaceRoot}/pkgs/akanjs/ui`, "akanjs/ui", "recipe");
  const recipes = scanRecipes(sources);
  const scopeIndexPointer = `App and lib recipes are **not** listed here. Each app/lib carries its own generated index —
\`apps/<app>/AGENTS.md\` / \`libs/<lib>/AGENTS.md\` (\`## Recipes In Scope\`) — regenerated by \`akan sync\` and
verified by \`akan lint\`. When working inside an app or lib, consult that file before consuming or authoring a look.`;
  if (recipes.length === 0) return `## Recipes\n\n${scopeIndexPointer}\n\n`;
  return `## Recipes

Framework UI recipes (Tailwind-variant look factories), importable from every app and lib: \`import { <name> } from
"akanjs/ui"\`, then \`<name>(variants?, className?)\`. The second arg merges internally and takes **an array too**, so
never wrap it in \`cn()\`: \`<name>({}, ["h-full", isWide && "w-full", className])\`. The list below is the full
contract (\`*\` marks the default, \`key?\` is a boolean flag) — do not guess a name, path, or variant value, and do
not open the recipe file to consume one. **Before inlining a repeated surface (card, box, tile, …): reuse a recipe,
or add one as \`apps/<app>/ui/Recipe/<name>.ts\`, one per file, re-exported from that folder's \`index.ts\` — never
re-implement the same look inline in several places, and never author a near-duplicate.** Full policy: the
\`recipeRule\` guideline.

${renderRecipeEntries(recipes)}

${scopeIndexPointer}

`;
};

// Onboarding is skipped in the framework monorepo: it teaches building *on* Akan, and would more than double an
// always-loaded file for readers who are changing Akan.
const renderGuides = async (context: AkanWorkspaceContext) => {
  const conventions = (await Prompter.getInstruction("conventions")).trim();
  if (context.pkgs.some((pkg) => pkg.name === "akanjs")) return conventions;
  const onboarding = (await Prompter.getInstruction("workspaceOnboarding")).trim();
  const appName = context.apps[0]?.name ?? "app";
  return `${conventions}\n\n${onboarding.replaceAll("<%= appName %>", appName)}`;
};

const renderManagedBlock = async (workspace: Workspace) => {
  const context = await AkanContextAnalyzer.analyze(workspace);
  const frameworkGuide = await Prompter.getInstruction("framework");
  const appNames = context.apps.map((app) => app.name);
  const sampleCleanup = await renderSampleCleanup(workspace, appNames);
  const recipeIndex = await renderRecipeIndex(workspace);
  const guides = await renderGuides(context);
  const version = await readDevkitVersion();
  const block = `## Workspace

- Repo: ${context.repoName}
- Apps: ${appNames.join(", ") || "none"}
- Libraries: ${context.libs.map((lib) => lib.name).join(", ") || "none"}
- Packages: ${context.pkgs.map((pkg) => pkg.name).join(", ") || "none"}

${guides}

${sampleCleanup}## Akan Module Abstracts

- Before changing a domain, service, or scalar module, read its \`*.abstract.md\` file first.
- Update the abstract when business invariants, workflows, or public behavior change.
- Do not update the abstract for formatting-only, import-only, or style-only changes.
- Service modules live in \`lib/_<service>\`, but their abstract file is \`<service>.abstract.md\`.
- Keep an abstract short — the invariants the code cannot show, and nothing it already states. \`akan quality scan\` warns past 300 lines.

## Generated Files

Do not hand-edit generated Akan files such as ${context.generatedFiles.map((file) => `\`${file}\``).join(", ")}.
If generated output is stale or broken, update the owning source file and run \`akan repair generated\` or \`akan sync <app-or-lib>\`.

${recipeIndex}## MCP Workflow Policy

- **Prefer an Akan workflow to a direct source edit.** A direct edit is denied when an allowlisted workflow or repair tool can make the change.
- Inspect with \`akan mcp --mode plan\` (\`list_workflows\`, \`explain_workflow\`, \`plan_workflow\`); apply with \`akan mcp --mode apply\`, which allowlists \`apply_workflow\`, \`run_validation\`, and three of the five repair tools — \`repair_generated\`, \`repair_imports\` and \`repair_module_shape\`. \`akan repair format\` and \`akan repair dictionary\` are CLI-only.
- If \`plan_workflow\` returns \`planPath\` or \`next.tool=apply_workflow\`, call \`apply_workflow({ planPath })\` before editing source. Then run \`run_validation\` with \`validationTarget\` when present, otherwise \`applyReportPath\`.
- Split a compound request into workflows and apply each \`planPath\` in order, such as \`create-module\` followed by \`add-field\`.
- When no workflow exists, or apply reports unsupported/no-op/failed diagnostics needing manual action, keep edits scoped to owning source files and never patch generated files directly.
- **MCP not connected?** The CLI is a first-class equivalent — \`akan workflow list\` / \`explain\` / \`plan\` / \`apply\`, \`akan doctor\`, \`akan repair\`. See the onboarding guide's CLI-only fallback for the exact flags.

## Validation

${context.validationCommands.map((command) => `- \`${command}\``).join("\n")}

## Framework Guide

${frameworkGuide.trim()}

## Before You Finish

1. \`bun run akan lint <appName>\` — Tailwind class order, \`Err\`, \`console\`, \`#private\` scope, unused imports.
2. \`bun run akan typecheck <appName>\` — server/client boundary violations, and the tests and specs nothing imports.
3. \`bun run akan sync <appName>\` if you added, renamed, or deleted any file.
4. Did you write or change a \`.tsx\` file? \`bun run akan quality ssr\` — did the server share hold, and did you add
   a \`"use client"\` you cannot justify?
5. Re-read the file you wrote against its section above.
6. Did you add a comment? Delete it unless it documents an external constraint or a security decision.
7. Did behavior or an invariant change? Update the module's \`*.abstract.md\`.`;
  return version ? stampBlockVersion(block, version) : block;
};

const renderAgentsMd = async (workspace: Workspace, existing: string | null) => {
  const block = await renderManagedBlock(workspace);
  if (existing?.trim()) return upsertAgentBlock(existing, block);
  const context = await AkanContextAnalyzer.analyze(workspace);
  return `# ${context.repoName} Agent Guide

This file is the single source of truth for coding agents in this workspace. Claude Code reads it through
\`CLAUDE.md\` (\`@AGENTS.md\`) and Cursor through \`.cursor/rules/akan.mdc\`. The section between the
\`akan:agent\` markers is regenerated by \`akan agent install\`; edit anything outside the markers freely.

${AGENT_BLOCK_START}
${block}
${AGENT_BLOCK_END}
`;
};

// Claude Code imports files with `@path`, so CLAUDE.md stays a pointer; only the comment rule is restated.
const renderClaudeMd = async (workspace: Workspace) => {
  const context = await AkanContextAnalyzer.analyze(workspace);
  return `# ${context.repoName} — Claude Code Guide

@AGENTS.md

${CLAUDE_COMMENT_RULE}
`;
};

const renderCursorRule = () => `---
description: Akan workspace agent guide
alwaysApply: true
---

Follow the workspace agent guide, which is the single source of truth for Akan conventions,
generated-file rules, and the MCP workflow policy.

@AGENTS.md
`;

const renderTarget = async (workspace: Workspace, target: AgentTarget, existing: string | null) => {
  if (target === "agents-md") return await renderAgentsMd(workspace, existing);
  if (target === "claude") return await renderClaudeMd(workspace);
  return renderCursorRule();
};

export class AgentRunner extends runner("agent") {
  async install(workspace: Workspace, targets: AgentTarget[], { force = false }: { force?: boolean } = {}) {
    const written: string[] = [];
    for (const target of targets) {
      const filePath = targetPaths[target];
      const exists = await workspace.exists(filePath);
      // AGENTS.md rewrites only its managed block; the CLAUDE.md and Cursor pointers need --force to overwrite.
      if (exists && !force && target !== "agents-md") {
        throw new Error(`${filePath} already exists. Re-run with --force to overwrite it.`);
      }
      const existing = exists ? await workspace.readFile(filePath) : null;
      const content = await renderTarget(workspace, target, existing);
      await workspace.writeFile(filePath, content, { overwrite: true });
      written.push(filePath);
    }
    if (targets.includes("agents-md")) written.push(...(await this.#installScopeIndexes(workspace)));
    return written;
  }

  // First-time layout; `akan sync` keeps them fresh. Best-effort per scope: one whose config/env cannot load yet
  // must not block the workspace-level install.
  async #installScopeIndexes(workspace: Workspace) {
    const [appNames, libNames] = await workspace.getExecs();
    const written: string[] = [];
    const syncScope = async (exec: AppExecutor | LibExecutor) => {
      try {
        await exec.syncAgentsIndex();
        written.push(`${exec.type}s/${exec.name}/AGENTS.md`);
      } catch (error) {
        const message = error instanceof Error ? error.message : String(error);
        Logger.rawLog(`Skipped ${exec.type}s/${exec.name}/AGENTS.md (${message})`, undefined, "error");
      }
    };
    for (const name of libNames) await syncScope(LibExecutor.from(workspace, name));
    for (const name of appNames) await syncScope(AppExecutor.from(workspace, name));
    return written;
  }
}
