// akan-native build linux --installer: beside the AppImage, a tar.gz that installs the app folder for one user. An
// AppImage runs from a read-only image, so only the folder is an app the updates plugin can replace.
//
//   <fileName>-<version>-<arch>.tar.gz
//     <fileName>-<version>-<arch>/
//       install.sh      puts the app folder in place and makes its launcher entry, icon and command
//       uninstall.sh    removes them; install.sh leaves a copy beside the installed app folder
//       <fileName>/     the app folder as `build linux` makes it
//
// - Per user, no root: $HOME/.local/opt/<app id>/<fileName>. The updates plugin unpacks `<fileName>.update-<bundle>`
//   beside the app folder and keeps `<fileName>.previous` there, so the parent is the user's and holds this app alone.
//   A folder root owns is one that updater cannot replace, so install.sh refuses root unless --allow-root.
// - install.sh over an install upgrades it: the new folder is copied beside the old one (`<fileName>.new-<pid>`) and
//   takes its place by two renames, the old one waiting in `<fileName>.replaced-<pid>`; a step that fails, or a
//   signal, puts the old folder back. The updater's own siblings are not touched.
// - The launcher entry is $XDG_DATA_HOME/applications/<app id>.desktop, the file the app rewrites for its deep links
//   at every start (packages/desktop/src/deeplinks.ts). INSTALLED_MARKER in it keeps that rewrite a visible entry.
// - uninstall.sh lies in the parent, not the app folder, which an update replaces whole. It removes the launcher
//   entry only when install.sh made it or it starts this install, and keeps the app's data unless --purge, the
//   updater's own folder in it aside.
// - Both are POSIX sh (dash is /bin/sh on Debian and Ubuntu). A value from the config reaches them only as a
//   single-quoted assignment at the top: never in a comment, where a line break in a name would end the comment.

import { chmodSync, cpSync, mkdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { INSTALLED_MARKER } from "../../../desktop/src/deeplinks.ts";
import { execOrThrow } from "../lib/exec.ts";
import { CliError, log } from "../lib/log.ts";
import type { BuildContext } from "../lib/prepare.ts";
import { targetArch } from "./desktop.ts";

export interface LinuxInstallInput {
  id: string;
  name: string;
  fileName: string;
  version: string;
  /** deepLinks.schemes: the launcher entry's x-scheme-handler MIME types. */
  schemes: string[];
}

/** A POSIX sh single-quoted word: nothing in it expands, and a quote ends the word, is escaped, and starts it again. */
export const shellQuote = (value: string) => `'${value.replace(/'/g, "'\\''")}'`;

/** A Desktop Entry string value: one line, with the backslash the format escapes with doubled. */
const entryValue = (value: string) => value.replace(/\\/g, "\\\\").replace(/\n/g, "\\n").replace(/\r/g, "\\r");

const COMMON = `
fail() {
  printf '%s\\n' "$*" >&2
  exit 1
}

warn() {
  printf '%s\\n' "warning: $*" >&2
}

# An XDG base directory must be absolute; anything else is ignored (XDG Base Directory spec).
xdg() {
  case "$1" in
    /*) printf '%s' "$1" ;;
    *) printf '%s' "$2" ;;
  esac
}

refresh_caches() {
  if command -v update-desktop-database > /dev/null 2>&1; then
    update-desktop-database "$DATA_HOME/applications" > /dev/null 2>&1 || :
  fi
  if command -v gtk-update-icon-cache > /dev/null 2>&1; then
    gtk-update-icon-cache -q -t -f "$DATA_HOME/icons/hicolor" > /dev/null 2>&1 || :
  fi
}

[ -n "\${HOME:-}" ] || fail "HOME is not set"
DATA_HOME=$(xdg "\${XDG_DATA_HOME:-}" "$HOME/.local/share")
ENTRY="$DATA_HOME/applications/$APP_ID.desktop"
ICON="$DATA_HOME/icons/hicolor/256x256/apps/$APP_ID.png"
BIN="$HOME/.local/bin/$FILE_NAME"
# Folders are named without symbolic links (pwd -P), as the running app names its own: uninstall.sh compares them.
HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd -P)
`;

//? The app id and the file name are folders the scripts remove: an empty one, or one with a "/", would name another.
const FOLDER_NAME = /^[A-Za-z0-9][A-Za-z0-9._-]*$/;

function head(input: LinuxInstallInput): string {
  for (const name of [input.id, input.fileName])
    if (!FOLDER_NAME.test(name)) throw new CliError(`${JSON.stringify(name)} cannot name the installed app's folder`);
  return `#!/bin/sh
# Generated by akan-native build linux --installer.
set -eu

APP_ID=${shellQuote(input.id)}
APP_NAME=${shellQuote(input.name)}
ENTRY_NAME=${shellQuote(entryValue(input.name))}
FILE_NAME=${shellQuote(input.fileName)}
VERSION=${shellQuote(input.version)}
MIME_TYPES=${shellQuote(input.schemes.map((scheme) => `x-scheme-handler/${scheme};`).join(""))}
${COMMON}`;
}

const INSTALL = `
usage() {
  printf '%s\\n' "usage: $0 [--dir <folder>] [--allow-root]" \\
    "Installs $APP_NAME $VERSION for this user in <folder>/$FILE_NAME (default: $HOME/.local/opt/$APP_ID)."
}

PARENT=
ALLOW_ROOT=0
while [ "$#" -gt 0 ]; do
  case "$1" in
    --dir)
      [ "$#" -ge 2 ] || fail "--dir takes a folder"
      PARENT=$2
      shift 2
      ;;
    --dir=*)
      PARENT=\${1#--dir=}
      shift
      ;;
    --allow-root)
      ALLOW_ROOT=1
      shift
      ;;
    -h | --help)
      usage
      exit 0
      ;;
    *)
      usage >&2
      exit 2
      ;;
  esac
done

if [ "$(id -u)" = 0 ] && [ "$ALLOW_ROOT" = 0 ]; then
  fail "run install.sh as the user who uses $APP_NAME, not as root: the app's updater cannot replace a folder root owns (--allow-root installs for root itself)"
fi

SRC="$HERE/$FILE_NAME"
[ -f "$SRC/$FILE_NAME" ] || fail "$SRC/$FILE_NAME is missing: run install.sh in the folder the archive unpacked into"
[ -n "$PARENT" ] || PARENT="$HOME/.local/opt/$APP_ID"
mkdir -p "$PARENT"
PARENT=$(CDPATH= cd -- "$PARENT" && pwd -P)
[ "$PARENT" != "$HERE" ] || fail "$PARENT is the unpacked archive: pick another --dir"
APP="$PARENT/$FILE_NAME"
NEW="$APP.new-$$"
OLD="$APP.replaced-$$"
if [ -e "$APP" ] && [ ! -f "$APP/$FILE_NAME" ]; then
  fail "$APP holds something other than $APP_NAME: pick another --dir"
fi

# What an install.sh that was killed left, named by its process id; one cut off between its two renames left the
# app only in .replaced-<pid>. A process id that is alive is another install.sh at work.
for left in "$APP".replaced-* "$APP".new-*; do
  [ -e "$left" ] || continue
  pid=\${left##*-}
  if [ "$pid" != "$$" ] && kill -0 "$pid" 2> /dev/null; then continue; fi
  case "$left" in
    "$APP".replaced-*)
      if [ ! -e "$APP" ] && [ -f "$left/$FILE_NAME" ]; then
        mv "$left" "$APP"
        continue
      fi
      ;;
  esac
  rm -rf "$left"
done

restore() {
  if [ ! -e "$APP" ] && [ -e "$OLD" ]; then
    mv "$OLD" "$APP" || warn "$APP_NAME could not be moved back: it is in $OLD, which the next install.sh puts back"
  fi
  rm -rf "$NEW"
}
trap restore EXIT
trap 'exit 129' HUP
trap 'exit 130' INT
trap 'exit 143' TERM

cp -RPp "$SRC" "$NEW" || fail "$APP_NAME could not be copied into $PARENT"
UPGRADE=0
if [ -e "$APP" ]; then
  UPGRADE=1
  mv "$APP" "$OLD" || fail "$APP could not be moved aside: $APP_NAME is left as it was"
fi
mv "$NEW" "$APP" || fail "the new files could not be moved to $APP: $APP_NAME is left as it was"
rm -rf "$OLD" || warn "$OLD, the app before this install, could not be removed"
trap - EXIT HUP INT TERM

cp "$HERE/uninstall.sh" "$PARENT/uninstall.sh" && chmod 755 "$PARENT/uninstall.sh" ||
  warn "uninstall.sh could not be copied into $PARENT"

# The Exec key's quoting (Desktop Entry spec): inside the double quotes \\ " \` $ take a backslash, a string value
# then doubles every backslash, and a literal % is %%.
desktop_quote() {
  printf '%s' "$1" | sed -e 's/[\\\\"\`$]/\\\\&/g' -e 's/\\\\/\\\\\\\\/g' -e 's/%/%%/g'
}

write_entry() {
  mkdir -p "$DATA_HOME/applications" || return
  {
    printf '%s\\n' '[Desktop Entry]' 'Type=Application' "Name=$ENTRY_NAME"
    printf 'Exec="%s" %%u\\n' "$(desktop_quote "$APP/$FILE_NAME")"
    printf '%s\\n' "Icon=$APP_ID" "StartupWMClass=$APP_ID" 'Terminal=false' 'Categories=Utility;'
    if [ -n "$MIME_TYPES" ]; then printf '%s\\n' "MimeType=$MIME_TYPES"; fi
    printf '%s\\n' '${INSTALLED_MARKER}'
  } > "$ENTRY.tmp-$$" && mv -f "$ENTRY.tmp-$$" "$ENTRY"
}
write_entry || warn "the launcher entry $ENTRY could not be written"

if [ -f "$APP/resources/icon.png" ]; then
  mkdir -p "\${ICON%/*}" && cp "$APP/resources/icon.png" "$ICON" || warn "the icon could not be copied to $ICON"
fi

# A link an earlier install.sh made ends in <fileName>/<fileName>, wherever that install was.
OURS=0
if [ -L "$BIN" ]; then
  case "$(readlink "$BIN")" in
    */"$FILE_NAME"/"$FILE_NAME") OURS=1 ;;
  esac
elif [ ! -e "$BIN" ]; then
  OURS=1
fi
if [ "$OURS" = 1 ]; then
  mkdir -p "\${BIN%/*}" && rm -f "$BIN" && ln -s "$APP/$FILE_NAME" "$BIN" || warn "$BIN could not be linked to the app"
else
  warn "$BIN is not a link install.sh made, so it stays as it is: start $APP_NAME from the launcher, or as $APP/$FILE_NAME"
fi

refresh_caches
RESTART=
[ "$UPGRADE" = 0 ] || RESTART=" A copy that is running keeps the old version until it is restarted."
printf '%s\\n' "$APP_NAME $VERSION is installed in $APP.$RESTART Uninstall it with $PARENT/uninstall.sh"
`;

const UNINSTALL = `
usage() {
  printf '%s\\n' "usage: $0 [--dir <folder>] [--purge]" \\
    "Removes $APP_NAME from <folder> (default: the folder of an installed uninstall.sh, else $HOME/.local/opt/$APP_ID)." \\
    "--purge removes the app's data too."
}

PARENT=
PURGE=0
while [ "$#" -gt 0 ]; do
  case "$1" in
    --dir)
      [ "$#" -ge 2 ] || fail "--dir takes a folder"
      PARENT=$2
      shift 2
      ;;
    --dir=*)
      PARENT=\${1#--dir=}
      shift
      ;;
    --purge)
      PURGE=1
      shift
      ;;
    -h | --help)
      usage
      exit 0
      ;;
    *)
      usage >&2
      exit 2
      ;;
  esac
done

CONFIG_HOME=$(xdg "\${XDG_CONFIG_HOME:-}" "$HOME/.config")
CACHE_HOME=$(xdg "\${XDG_CACHE_HOME:-}" "$HOME/.cache")
DATA="$DATA_HOME/$APP_ID"
CACHE="$CACHE_HOME/$APP_ID"
AUTOSTART="$CONFIG_HOME/autostart/$APP_ID.desktop"
LIST="$CONFIG_HOME/mimeapps.list"

# install.sh lies beside the archive's copy of this script; the installed copy lies in the install's own parent.
if [ -z "$PARENT" ]; then
  if [ -f "$HERE/install.sh" ]; then PARENT="$HOME/.local/opt/$APP_ID"; else PARENT=$HERE; fi
fi
if [ -d "$PARENT" ]; then PARENT=$(CDPATH= cd -- "$PARENT" && pwd -P); fi
[ ! -f "$PARENT/install.sh" ] || fail "$PARENT is the unpacked archive, not an install"
APP="$PARENT/$FILE_NAME"
FOUND=1
if [ -e "$APP" ]; then
  [ -f "$APP/$FILE_NAME" ] || fail "$APP holds something other than $APP_NAME: nothing is removed"
elif [ ! -f "$PARENT/uninstall.sh" ]; then
  [ "$PURGE" = 1 ] || fail "$APP_NAME is not installed in $PARENT (an install elsewhere: --dir <folder>)"
  FOUND=0
fi

starts_install() {
  [ -f "$1" ] && grep '^Exec=' "$1" | grep -q -F "$APP/"
}

if [ "$FOUND" = 1 ]; then
  rm -rf "$APP" "$APP.previous" "$APP".update-* "$APP".failed-* "$APP".replaced-* "$APP".new-* ||
    fail "$APP could not be removed"
  # The updater's downloads and its record of this install (a trial, its strikes), as the Windows uninstaller removes
  # them: an install made later is not this one.
  rm -rf "$DATA/akan-native-updates" "$DATA/akan-native-updates-debug" || :

  if [ -f "$ENTRY" ] && { grep -q -x -F '${INSTALLED_MARKER}' "$ENTRY" || starts_install "$ENTRY"; }; then
    rm -f "$ENTRY"
  fi
  # An entry that stays is another copy's (an AppImage of the app), and so are its icon and the defaults naming it.
  if [ ! -e "$ENTRY" ]; then
    rm -f "$ICON"
    if [ -f "$LIST" ] && grep -q -F "$APP_ID.desktop" "$LIST"; then
      DESKTOP_FILE="$APP_ID.desktop" awk '{
        at = index($0, "=")
        if (at == 0) { print; next }
        n = split(substr($0, at + 1), items, ";")
        kept = ""
        dropped = 0
        for (i = 1; i <= n; i++) {
          if (items[i] == ENVIRON["DESKTOP_FILE"]) dropped = 1
          else if (items[i] != "") kept = kept items[i] ";"
        }
        if (!dropped) print
        else if (kept != "") print substr($0, 1, at) kept
      }' "$LIST" > "$LIST.tmp-$$" && cat "$LIST.tmp-$$" > "$LIST" || warn "$LIST still names $APP_ID.desktop"
      rm -f "$LIST.tmp-$$"
    fi
  fi
  if starts_install "$AUTOSTART"; then rm -f "$AUTOSTART"; fi
  if [ -L "$BIN" ]; then
    case "$(readlink "$BIN")" in
      "$APP"/*) rm -f "$BIN" ;;
    esac
  fi
  refresh_caches
  rm -f "$PARENT/uninstall.sh"
  rmdir "$PARENT" 2> /dev/null || :
fi

if [ "$PURGE" = 1 ]; then
  rm -rf "$DATA" "$CACHE" || warn "the data in $DATA and $CACHE could not all be removed"
  DATA_NOTE=" Its data is removed too."
elif [ -d "$DATA" ] || [ -d "$CACHE" ]; then
  DATA_NOTE=" Its data stays in $DATA and $CACHE (--purge removes it too)."
else
  DATA_NOTE=
fi
if [ "$FOUND" = 1 ]; then
  printf '%s\\n' "$APP_NAME is uninstalled from $PARENT.$DATA_NOTE"
else
  printf '%s\\n' "$APP_NAME is not installed in $PARENT.$DATA_NOTE"
fi
`;

export const installScript = (input: LinuxInstallInput): string => `${head(input)}${INSTALL}`;

export const uninstallScript = (input: LinuxInstallInput): string => `${head(input)}${UNINSTALL}`;

/** Writes the tar.gz beside the app folder and answers its path. */
export async function buildLinuxInstaller(ctx: BuildContext, folder: string): Promise<string> {
  const { app, deepLinks } = ctx.project.config;
  const input = {
    id: app.id,
    name: app.name,
    fileName: app.fileName,
    version: app.version,
    schemes: deepLinks.schemes,
  };
  const top = `${app.fileName}-${app.version}-${targetArch(ctx)}`;
  const gen = join(ctx.outDir, "gen");
  const stage = join(gen, top);
  rmSync(stage, { recursive: true, force: true });
  mkdirSync(stage, { recursive: true });
  cpSync(folder, join(stage, app.fileName), { recursive: true, verbatimSymlinks: true });
  for (const [name, text] of [
    ["install.sh", installScript(input)],
    ["uninstall.sh", uninstallScript(input)],
  ] as const) {
    writeFileSync(join(stage, name), text);
    chmodSync(join(stage, name), 0o755);
  }

  log.step("installer: tar.gz");
  const outFile = join(ctx.outDir, `${top}.tar.gz`);
  await execOrThrow(["tar", "-czf", outFile, "-C", gen, top], { echo: false });
  rmSync(stage, { recursive: true, force: true });
  log.info(`installer ${outFile} (${Math.round(statSync(outFile).size / 1024 / 1024)} MB)`);
  return outFile;
}
